# Модель нагрузки 1000 одновременных (R227). b_cam — средняя камера, scr — показ (+0,26 звук показа с RED), voice 0,13 на говорящего на подписчика.
VOICE=0.13; SCRA=0.26
def room(N, cam_share, share_p, b_cam, b_scr, speakers=1.5, music=0.0):
    cams = N*cam_share
    eg = cams*(N-1)*b_cam + share_p*(N-1)*(b_scr+SCRA) + speakers*(N-1)*VOICE + music*N*0.5
    ing = cams*b_cam + share_p*(b_scr+SCRA) + speakers*VOICE*1.0 + 0.02*N
    subs_v = cams*(N-1) + share_p*(N-1)
    subs_a = speakers*(N-1)
    return eg, ing, subs_v, subs_a
def mix(name, classes):
    E=I=P=SV=SA=R=0
    for (label, people, N, cs, sp, bc, bs, mus) in classes:
        rooms = people/N; e,i,sv,sa = room(N,cs,sp,bc,bs,music=mus)
        E+=rooms*e; I+=rooms*i; SV+=rooms*sv; SA+=rooms*sa; P+=people; R+=rooms
        print(f"  {label:28s} люди {people:5.0f} комнат {rooms:5.0f} отдача {rooms*e:6.0f} Мбит/с ({e:5.1f} на комнату)")
    pps = E*1e6/8/1100*0.9 + SA*50  # видео ~1100 Б, звук 50 пак/с на подписку
    print(f"{name}: люди {P:.0f}, комнат {R:.0f}, SFU отдача {E:.0f} Мбит/с, приём {I:.0f}, на человека {E/P:.2f}; видеоподписок {SV:.0f}, звуковых {SA:.0f}; ~{pps/1000:.0f} тыс. пак/с отдачи")
    return E
