-- «Посетитель» прежней аналитики — любой профиль устройства, приславший «открыл Cord»: роботы, сканеры и свои
-- автотесты давали 84 % строк. Людей и их дни теперь считает служба `insight` в своей схеме по фактам ядра
-- (`contracts/insight.md`); ядро хранит только то, что нужно самим встречам и владельцу: журнал участников
-- (`meeting_participants`), аудит, обращения.
DROP TABLE visitor_days;
DROP TABLE visitors;

-- История встреч начинается вместе с новой аналитикой: строки встреч прежнего счёта стираются. Идущая встреча
-- заведёт свою строку заново первым же событием (`MeetingStats.row`).
DELETE FROM meeting_stats;

-- Срок сообщений (R236, docs/architecture/core-scale.md §3.1). Секундный проход удалял просроченное одним
-- запросом `created_at<=? OR expires_at<=?` — без индекса ни по одному из двух столбцов, то есть полным
-- просмотром переписки всех встреч раз в секунду. Теперь удалений два, и у каждого свой индекс.
CREATE INDEX message_expiry ON messages(expires_at);
CREATE INDEX message_created ON messages(created_at);
