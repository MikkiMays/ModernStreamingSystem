-- Когда в комнате последний раз был человек.
--
-- ЗАЧЕМ ОТДЕЛЬНЫЙ СТОЛБЕЦ, А НЕ `updated_at`. Тот отвечает на другой вопрос — «когда
-- строку последний раз писали», — и ответ у него бывает свежим у комнаты, где год никого
-- не было: её переписывает уборка. По нему нельзя ни удалить забытое, ни просто посмотреть,
-- что близко к удалению.
--
-- Значение считает `RoomState.lastSeenAt` — одно место на весь проект, — и попадает оно
-- сюда при каждом сохранении комнаты. Поэтому разойтись со снимком оно не может: это не
-- вторая запись того же факта, а тот же факт, вынесенный туда, где его можно спросить.
--
-- ЧТО ЗДЕСЬ ТОЧНО, А ЧТО ПРИБЛИЗИТЕЛЬНО. Комната сохраняется, когда меняется, — значит у
-- пустой и закрытой отметка точная и больше не сдвинется, а у идущей встречи она отстаёт
-- на время, прошедшее с последнего события в ней. Решение об удалении это не трогает: его
-- принимает `Lifecycle` по свежему снимку, и комнату, где сидят люди, оно не тронет никогда.
-- Но запрос «что скоро удалится» стоит ограничивать закрытыми комнатами.
--
-- Существующим комнатам достаётся `updated_at`: настоящей отметки у них нет, а нулевая
-- означала бы «забыта в 1970 году» и снесла бы их все в первую же минуту после выкладки.
ALTER TABLE rooms ADD COLUMN last_seen_at BIGINT NOT NULL DEFAULT 0;
UPDATE rooms SET last_seen_at = updated_at;
CREATE INDEX room_idle ON rooms(last_seen_at);
