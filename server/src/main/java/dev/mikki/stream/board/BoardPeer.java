package dev.mikki.stream.board;

/**
 * Участник у доски — один открытый сокет (R159). Доска раскладывает по участникам правки и
 * эфемерное; как это доходит до браузера (очередь, обратное давление), решает сокет ({@link
 * Outbox}).
 */
public interface BoardPeer {
  /** Кто это во встрече. */
  String memberId();

  /**
   * Надёжное сообщение: правки, сцена, очистка. Не теряется; не помещается в очередь — сокет
   * закрыт.
   */
  void send(String message);

  /** Эфемерное: курсор, лазер, штрих «в процессе». Схлопывается, может потеряться. */
  void ephemeral(Ephemeral message);

  /** Закрыть сокет: доски больше нет, права отозваны, комната удалена. */
  void close(String code);
}
