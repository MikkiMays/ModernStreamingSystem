package dev.mikki.stream.room;

/**
 * Комната изменилась сама по себе — не потому, что кто-то прислал команду.
 *
 * <p>Обычное изменение объявляет тот, кто его вызвал: команда приходит по сокету, и он же рассылает
 * её последствия. У сроков такого адресата нет: истёкшее восстановление, конец хода за столом,
 * следующая раздача — всё это происходит на сервере, и без этого объявления комната узнала бы о них
 * только на следующем секундном проходе сокетов. Для встречи секунда незаметна, для карточного
 * стола — это «подвисло».
 *
 * <p>Слушает {@code RoomSocket}, и слушает <b>после фиксации</b> транзакции: разослать снимок
 * раньше, чем он записан, значит разослать предыдущий.
 */
public record RoomChanged(String roomId) {}
