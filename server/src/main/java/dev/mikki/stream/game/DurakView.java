package dev.mikki.stream.game;

import java.util.List;

/**
 * Стол дурака таким, каким его вправе видеть один конкретный человек.
 *
 * <p>ЗДЕСЬ НЕТ ТРЁХ ВЕЩЕЙ, И ЭТО ГЛАВНОЕ ПРО ВЕСЬ ФАЙЛ: колоды, зерна тасовки и чужих рук. Они
 * остаются в снимке комнаты на сервере и не уходят в браузер ни одним полем — иначе «посмотреть
 * чужие карты» означало бы открыть инструменты разработчика. О чужой руке известно ровно одно
 * число: сколько в ней карт ({@code held}), — столько рубашек и рисуется.
 *
 * <p>ЗАКОННЫХ КАРТ ЗДЕСЬ ТОЖЕ НЕТ, И ЭТО РЕШЕНИЕ, А НЕ УПУЩЕНИЕ. Первая версия присылала три списка
 * — чем пойти, чем побить каждую атаку, чем перевести, — и браузер подсвечивал ими руку. За
 * настоящим столом никто не подсвечивает: человек берёт карту и кладёт, а если она не ложится, он
 * забирает её обратно. Снимок несёт только {@code actions} — слова для кнопок «Беру» и «Бито»;
 * законность хода по-прежнему решает сервер, но узнаёт о ней игрок <b>после</b> хода, а не до.
 */
public record DurakView(
    /** {@code podkidnoy} или {@code perevodnoy}. */
    String mode,
    String modeName,
    /** {@code lobby}, {@code bout} или {@code over}. */
    String phase,
    String hostId,
    /** 36 или 52 — сколько карт в колоде этого стола. */
    int deckSize,
    /** Разрешён ли перевод. То же самое, что {@code mode}, но одним флагом для кнопки. */
    boolean transfer,
    /** Подкидывают только соседи защитника. */
    boolean neighbours,
    /** Первый бой партии — не больше пяти карт. */
    boolean firstFive,
    int turnSeconds,
    boolean seatingOpen,
    long revision,
    /** Сколько партий сыграли за этим столом. */
    int handNumber,
    /** Козырная карта — та, что лежит под колодой лицом вверх. {@code null} до раздачи. */
    String trump,
    /** Масть козыря одной буквой: {@code s}, {@code h}, {@code d}, {@code c}. */
    String trumpSuit,
    /** Сколько карт осталось в колоде вместе с козырной. */
    int deckLeft,
    /** Сколько карт в отбое: по ним растёт стопка справа. */
    int discarded,
    int attacker,
    int defender,
    /**
     * От кого стол ждёт хода прямо сейчас.
     *
     * <p>Одно поле на два случая, и это не экономия. Пока есть неотбитая карта, ждут защитника —
     * место одно. Когда всё отбито, ждут <b>всех</b> нападающих разом: подкинуть или сказать
     * «бито». Разделить это на «чей ход» и «кто ещё думает» значило бы завести в снимке два понятия
     * там, где у стола одно: кольцо горит у того, от кого ждут.
     */
    List<Integer> acting,
    long actionAt,
    long deadline,
    /** Защитник сказал «беру»: карты уже его, но подкинуть ещё можно. */
    boolean taking,
    /** Сколько карт всего можно положить в этот бой. */
    int limit,
    /**
     * Чем кончился бой, который ещё лежит на столе: {@code beaten}, {@code taken} или {@code null}.
     *
     * <p>Бой не исчезает в тот же миг, когда закрылся: полторы секунды карты остаются на сукне и
     * уезжают в отбой или в руку — иначе «отбился» выглядит как мигание. Всё это время стол
     * бездействует, и по этому полю браузер понимает, что показывает не игру, а её конец.
     */
    String boutEnd,
    long boutAt,
    /** Когда начали раздавать: от этой метки идёт вся анимация полёта карт. */
    long dealtAt,
    /** Бой: атака и то, чем она побита. Порядок — тот, в котором карты клали. */
    List<CardPair> table,
    List<DurakSeat> seats,
    List<DurakNote> log,
    /** Что этот человек может сделать прямо сейчас. Для зрителя — {@code null}. */
    DurakYou you,
    /** Счёт беседы, от самого частого дурака к самому редкому. */
    List<DurakScore> score,
    /** Чем кончилась партия. Всё остальное время {@code null}. */
    DurakResult result,
    String commitment,
    /** Зерно тасовки — только после того, как партия сыграна. */
    String seed,
    /** Когда стол закроется сам, потому что за ним никого, или 0 — пока кто-то есть. */
    long closesAt) {

  /** Пара «атака — защита». {@code beat} пуст, пока карту не побили. */
  public record CardPair(String attack, String beat) {}

  /** Место за столом. Пустое место — это {@code memberId == null}. */
  public record DurakSeat(
      int index,
      String memberId,
      String name,
      /** Сколько карт на руках — по ним рисуются рубашки. */
      int held,
      boolean attacker,
      boolean defender,
      /** Сказал «бито» и в этот бой больше не подкидывает. */
      boolean passed,
      /** Вышел из партии: карты кончились, а колода уже пуста. */
      boolean out,
      /** Каким по счёту вышел, или 0 — ещё играет. */
      int place,
      boolean away,
      /** Тот самый. Видно только когда партия кончилась. */
      boolean fool) {}

  /** Строка ленты: что произошло и когда. */
  public record DurakNote(long at, String kind, int seat, String name, String text) {}

  public record DurakYou(
      int seat,
      /** Ваши карты в том порядке, в каком их удобно держать: по мастям, козыри справа. */
      List<String> cards,
      /**
       * Слова для кнопок: {@code take} и {@code pass}.
       *
       * <p>Кнопок ровно две, и обе — про то, чего нельзя сделать картой. Ходить, отбиваться и
       * переводить нечем нажимать: это движение карты, а не кнопка.
       */
      List<String> actions,
      /** Ждут ли хода именно от вас. */
      boolean turn) {}

  /**
   * Счёт беседы: сколько раз кто был дураком за этим столом.
   *
   * <p>Живёт в снимке, а не в истории, потому что отвечает на вопрос, который задают, не вставая:
   * «сколько там у меня». История — это про вечер, который уже кончился.
   */
  public record DurakScore(String name, int games, int fools, int streak) {}

  /**
   * Чем кончилась партия.
   *
   * <p>Дурак — один, и место у него есть всегда, кроме ничьей: когда последний бой опустошил руки
   * всем сразу, проигравшего не остаётся. Это законный конец, а не отсутствие результата.
   */
  public record DurakResult(
      long at, int foolSeat, String foolName, boolean draw, int bouts, List<String> places) {}
}
