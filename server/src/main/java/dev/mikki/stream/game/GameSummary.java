package dev.mikki.stream.game;

import com.fasterxml.jackson.annotation.JsonIgnoreProperties;
import java.util.List;

/**
 * Игра, которая кончилась.
 *
 * <p>ЭТО НЕ ЛОГ, А ИТОГ. Лента раздач живёт ровно столько, сколько идёт игра: «кто что сходил на
 * ривере» через день не нужно никому, а хранить это для десяти комнат означало бы держать в снимке
 * мегабайты текста. Здесь остаётся другое — с чем люди встали из-за стола: кто играл, сколько
 * докупался, сколько вложил, сколько раз пошёл ва-банк, и кто в чём оказался первым.
 *
 * <p>Запись неизменяемая и лежит в том же JSON комнаты, что и сам стол: своего хранилища у игры
 * по-прежнему нет, и история уходит вместе со встречей, как и всё остальное в ней. Неизвестные поля
 * пропускаются — иначе откат ядра сделал бы нечитаемой каждую комнату, где успели доиграть.
 */
@JsonIgnoreProperties(ignoreUnknown = true)
public record GameSummary(
    String id,
    String mode,
    String modeName,
    long startedAt,
    long finishedAt,
    /** Сколько раздач сыграли. Игра без раздач в историю не попадает вовсе. */
    int hands,
    long startingStack,
    long smallBlind,
    long bigBlind,
    int level,
    /** Самый крупный банк игры — тот, что видели все, а не чей-то личный. */
    long biggestPot,
    boolean tournament,
    /**
     * Чем кончилось. Ровно четыре конца, и других не бывает:
     *
     * <ul>
     *   <li>{@code winner} — за столом остался один;
     *   <li>{@code closed} — стол убрали из встречи руками;
     *   <li>{@code idle} — за столом десять минут никого не было;
     *   <li>{@code meeting} — встречу завершили, и стол ушёл вместе с ней.
     * </ul>
     *
     * <p>Строкой, а не перечислением, и это то же решение, что и с фазой игры: снимок комнаты
     * читается и той версией ядра, которая новых значений не знает, а неизвестная константа
     * перечисления сделала бы такую комнату нечитаемой целиком. Полноту проверяет браузер, где это
     * ничего не стоит ({@code PokerEnding} в {@code web/src/api/types.ts}).
     */
    String ending,
    List<PlayerSummary> players,
    List<Highlight> highlights) {

  /**
   * Один участник игры от начала до конца.
   *
   * <p>Ключ здесь — человек, а не место: он мог встать, сесть на другой стул и вернуться после
   * переподключения с новым идентификатором, и все три раза это один и тот же игрок.
   */
  @JsonIgnoreProperties(ignoreUnknown = true)
  public record PlayerSummary(
      String name,
      /** Место в турнире, или 0 — в дружеской игре мест нет. */
      int place,
      /** Сколько фишек взял всего: стартовый стек и все докупки. */
      long buyIn,
      /** Докупки — те самые «додепы». */
      int rebuys,
      /** С чем остался. */
      long stack,
      /** {@code stack - buyIn}: плюс или минус за игру. */
      long net,
      /** Сколько поставил за игру — всё, что уехало в банк. */
      long invested,
      long won,
      int hands,
      int handsWon,
      /** Сколько раз доходил до вскрытия и сколько из них выиграл. */
      int showdowns,
      int showdownWins,
      int allIns,
      int folds,
      int checks,
      int calls,
      int raises,
      /** Сколько раз добровольно вложился на префлопе: этим и меряется «азартный». */
      int voluntary,
      long biggestBet,
      long biggestPotWon,
      long peakStack,
      /** Скольких выбил из игры. */
      int knockouts,
      /** Самая длинная серия выигранных подряд раздач. */
      int bestStreak,
      /** Сильнейшая комбинация, которую показал на вскрытии. */
      String bestHand) {}

  /**
   * Прикольная строчка про игру.
   *
   * <p>Числа в таблице отвечают на «сколько», а это — на «кто». Именно их за столом и обсуждают:
   * кто сорвал самый крупный банк, кто чаще всех шёл ва-банк, кто досидел до конца, ни разу не
   * рискнув. Считаются они по тем же полям, что и таблица, поэтому спорить с ней не могут.
   */
  @JsonIgnoreProperties(ignoreUnknown = true)
  public record Highlight(String id, String title, String name, String value, String hint) {}
}
