package dev.mikki.stream.game;

import com.fasterxml.jackson.annotation.JsonIgnoreProperties;
import java.util.List;

/**
 * Партия дурака, которая кончилась.
 *
 * <p>ОДНА ЗАПИСЬ НЕСЁТ ДВА СЧЁТА, И ЭТО ГЛАВНОЕ ПРО ВЕСЬ ФАЙЛ. Первый — про саму партию: кто
 * оказался дураком, сколько было боёв, в каком порядке выходили. Второй — про всю беседу: сколько
 * раз кто был дураком за этим столом к моменту, когда партия кончилась. Второй лежит здесь же
 * нарочно: тогда счёт вечера читается из последней записи, и ни отдельной ручки, ни складывания
 * списка в браузере не нужно.
 *
 * <p>Ход партии не хранится вовсе: «кто чем отбился на третьем бою» через день не нужно никому, а
 * держать это для десяти комнат означало бы держать в снимке мегабайты текста.
 *
 * <p>Запись неизменяемая и лежит в том же JSON комнаты, что и стол: своего хранилища у игры
 * по-прежнему нет, и история уходит вместе со встречей. Неизвестные поля пропускаются — иначе откат
 * ядра сделал бы нечитаемой каждую комнату, где успели доиграть.
 */
@JsonIgnoreProperties(ignoreUnknown = true)
public record DurakSummary(
    String id,
    /** {@code podkidnoy} или {@code perevodnoy}. */
    String mode,
    String modeName,
    int deckSize,
    long startedAt,
    long finishedAt,
    /** Каким по счёту была эта партия за столом. */
    int number,
    /** Сколько боёв сыграли. */
    int bouts,
    /** Последний бой опустошил руки всем разом — дурака нет. */
    boolean draw,
    String foolName,
    /** Кто вышел и в каком порядке: от первого до дурака. */
    List<String> places,
    List<DurakPlayer> players,
    /** Прикольные строчки про вечер — те же, что у покера, и по тем же полям. */
    List<GameSummary.Highlight> highlights) {

  /**
   * Один участник: что он сделал в этой партии и с чем подошёл к ней за весь вечер.
   *
   * <p>Ключ — человек, а не место: он мог встать, пересесть и вернуться после переподключения с
   * новым идентификатором, и все три раза это один и тот же игрок.
   */
  @JsonIgnoreProperties(ignoreUnknown = true)
  public record DurakPlayer(
      String name,
      /** Он и есть дурак этой партии. */
      boolean fool,
      /** Каким вышел в этой партии, или 0 — не вышел вовсе. */
      int place,
      /** Сколько партий сыграл за этим столом. */
      int games,
      /** Сколько раз был дураком. Это и есть счёт беседы. */
      int fools,
      /** Сколько раз выходил первым. */
      int firsts,
      int takes,
      /** Сколько боёв отбил целиком, ни разу не взяв. */
      int defences,
      int thrown,
      /** Сколько козырей потратил на защиту. */
      int trumpsBurned,
      int transfers,
      /** Самая длинная серия партий без проигрыша. */
      int bestStreak) {}
}
