#!/bin/sh
# Браузер плеера страниц — первый, кого убирает нехватка памяти в контейнере: страница, которая съела
# память, должна уронить свою вкладку, а не сервер, который ею управляет. Поднять себе `oom_score_adj`
# процесс вправе сам, без привилегий; процессы браузера наследуют 1000, а GPU и рендереры Chromium по своему
# правилу опускает до 200 и 300 — всё равно выше сервера (0).
echo 1000 > /proc/self/oom_score_adj 2>/dev/null
exec /opt/chrome-headless-shell "$@"
