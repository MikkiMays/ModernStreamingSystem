/**
 * Видео замолчало, а SFU не сказал «пауза» (R119).
 *
 * ЗАЧЕМ. Живой замер 25.10: зрителю на канале 100 кбит/с SFU перестал слать камеру собеседника
 * (ни кадров, ни байт по этой дорожке 60 с подряд), речь при этом шла, а `StreamStateUpdate: PAUSED`
 * так и не пришёл — ни одного за всю встречу, хотя `allow_pause` запрошен и принят. Что бы ни решал
 * распределитель SFU, у зрителя это выглядит как застывший кадр без объяснения — ровно то, от чего
 * R117 и защищает. Поэтому кроме слова SFU есть свой признак: **камера** подписана, не выключена и не
 * заглушена, кадры из сети не приходят {@link SILENT_VIDEO_MS} подряд, а звук в это время приходит —
 * значит, картинку остановили, а не связь. Дальше пауза живёт по тем же правилам `video-pause.ts`:
 * надпись не раньше 700 мс, гаснет по первым новым кадрам.
 *
 * Только камера: показ экрана со статичным содержимым кадров не шлёт по своей природе (Chromium
 * кодирует только изменения), и тишина там — не пауза. Звук как свидетель нужен, чтобы отличить паузу
 * одной дорожки от обрыва всего пути: при обрыве молчит всё, и это чинит восстановление связи, а не надпись.
 */

/** Сколько подряд без новых кадров из сети, прежде чем счесть камеру остановленной. */
export const SILENT_VIDEO_MS = 4000;

export class VideoSilence {
  private frames?: number;
  private since?: number;

  /**
   * Принятые кадры дорожки (`framesReceived`) на этом опросе и идёт ли сейчас звук.
   * @returns true — кадров нет уже {@link SILENT_VIDEO_MS} при живом звуке: это пауза.
   */
  observe(framesReceived: number, audioFlowing: boolean, now: number): boolean {
    // Кадры пошли (или счётчики перезапущены новой подпиской) — отсчёт с начала.
    if (this.frames === undefined || framesReceived !== this.frames) {
      this.frames = framesReceived;
      this.since = now;
      return false;
    }
    // Без звука тишина камеры ничего не доказывает: отсчёт не копится, чтобы первая же секунда
    // звука не превратилась в «паузу» задним числом.
    if (!audioFlowing) {
      this.since = now;
      return false;
    }
    return now - (this.since ?? now) >= SILENT_VIDEO_MS;
  }
}
