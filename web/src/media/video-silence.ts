/**
 * Видео замолчало, а SFU не сказал «пауза» (R119, R189).
 *
 * ЗАЧЕМ. Живой замер 25.10: зрителю на канале 100 кбит/с SFU перестал слать камеру собеседника (ни кадров,
 * ни байт по этой дорожке 60 с подряд), речь при этом шла, а `StreamStateUpdate: PAUSED` так и не пришёл. У
 * зрителя это выглядит как застывший кадр без объяснения. Признак свой: **камера** подписана, не выключена и
 * не заглушена, а кадры из сети не приходят {@link SILENT_VIDEO_MS} подряд.
 *
 * ЧТО ЭТО ЗНАЧИТ. Только то, что кадров нет. Причину такая тишина не называет: камера могла встать у
 * отправителя, и тогда канал зрителя ни при чём. Поэтому у неё своя надпись («Картинка не обновляется», а не
 * «слабая связь», `video-pause.ts`) и звук свидетелем больше не нужен (R189): раньше без звука — например,
 * когда все с выключенными микрофонами — тишина камеры не считалась вовсе, и плитка стояла без слова.
 *
 * Только камера: показ экрана со статичным содержимым кадров не шлёт по своей природе (Chromium кодирует
 * только изменения), и тишина там — не пауза.
 */

/** Сколько подряд без новых кадров из сети, прежде чем счесть камеру замолчавшей. */
export const SILENT_VIDEO_MS = 4000;

export class VideoSilence {
  private frames?: number;
  private since?: number;

  /**
   * Принятые кадры дорожки (`framesReceived`) на этом опросе.
   * @returns true — кадров нет уже {@link SILENT_VIDEO_MS}.
   */
  observe(framesReceived: number, now: number): boolean {
    // Кадры пошли (или счётчики перезапущены новой подпиской) — отсчёт с начала.
    if (this.frames === undefined || framesReceived !== this.frames) {
      this.frames = framesReceived;
      this.since = now;
      return false;
    }
    return now - (this.since ?? now) >= SILENT_VIDEO_MS;
  }
}
