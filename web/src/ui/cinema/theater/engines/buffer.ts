/**
 * Сколько видео держать впереди и позади — «как у YouTube» (R172).
 *
 * ПОЧЕМУ НЕ ВЕСЬ ФИЛЬМ. Поток идёт к каждому зрителю через наш сервер, и всё, что загружено впрок, —
 * это полоса сервера, полоса зрителя рядом со звонком и память вкладки, которые пропадут зря, если
 * фильм закроют или перемотают. Поэтому вперёд — не больше полуминуты, а позади — ровно столько,
 * чтобы короткая отмотка не качала то же самое заново; остальное плеер отдаёт обратно.
 *
 * ПОЧЕМУ 20–30 С И В КАКУЮ СТОРОНУ. Канал с запасом (оценка полосы втрое и больше выше битрейта
 * ступени) — 30 с: дозагрузка идёт короткими рывками, а подушка переживает провал Wi-Fi. Канал впритык —
 * 20 с, как и до R172 (R151, «вежливый кинозал»): длинный хвост в низком качестве задержал бы подъём
 * ступени, а постоянная загрузка на пределе канала отнимала бы его у звонка. Пока оценки нет —
 * тоже 20 с: первый набор буфера во время звонка — самый тяжёлый.
 *
 * ГДЕ. hls.js — `maxBufferLength` и `maxMaxBufferLength` меняются на лету по каждому загруженному
 * кусочку (`attachHls`); dash.js — своей логикой «на верхней ступени — больше» (`attachDash`): там
 * верхняя ступень и значит, что канал с запасом. Готовый файл (`<video src>`) браузер буферизует сам —
 * Chromium держит впереди 15–20 с, — а служба отдаёт его кусками по 2 МБ (`FILE_CHUNK`), чтобы лишнего не
 * копили буферы сокетов: впереди 22 с вместо 65 (замер R172 — `backlog/knowledge/memory/cord-cinema-buffer.md`).
 */

/** Вперёд у канала впритык и пока полоса неизвестна, секунды. */
export const AHEAD_MIN = 20;
/** Вперёд у канала с запасом, секунды. */
export const AHEAD_MAX = 30;
/**
 * Позади текущего места, секунды: шаг назад пульта (← — 10 с, Shift+← — 30 с, `watch-keys.ts`) — без повторной
 * загрузки, остальное — из памяти прочь.
 */
export const BEHIND = 30;
/** Полоса во столько раз выше битрейта ступени — «впритык» и ниже. */
const TIGHT = 1.5;
/** Во столько раз и выше — «с запасом». */
const ROOMY = 3;

/**
 * Цель буфера вперёд по оценке полосы и битрейту играющей ступени (бит/с): 20 с впритык, 30 с с
 * запасом, между ними — по прямой, целыми секундами.
 */
export function aheadFor(bandwidth: number | null | undefined, bitrate: number | null | undefined): number {
  if (!bandwidth || !bitrate || !Number.isFinite(bandwidth) || !Number.isFinite(bitrate) || bitrate <= 0)
    return AHEAD_MIN;
  const ratio = bandwidth / bitrate;
  if (ratio <= TIGHT) return AHEAD_MIN;
  if (ratio >= ROOMY) return AHEAD_MAX;
  return Math.round(AHEAD_MIN + ((ratio - TIGHT) / (ROOMY - TIGHT)) * (AHEAD_MAX - AHEAD_MIN));
}
