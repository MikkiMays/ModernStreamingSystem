import type { VideoFamily } from '../decode';
import type { Health, Heal } from '../stall';
import type { Level } from '../watch-levels';

/**
 * Движок плеера, каким его видит кинозал: HLS (`hls.js`), DASH (`dash.js`) или адрес, который
 * браузер играет сам.
 *
 * Снаружи у них одно и то же: какие есть ступени качества, как переключить ступень и голос, где
 * край эфира и как убрать движок за собой. Разница остаётся внутри: о ступенях и дорожках каждый
 * узнаёт по-своему и сообщает о них своими обратными вызовами (`attachHls`, `attachDash`).
 * Необязательное есть не у всех — у кого нет, у того и прежде этого не было.
 */
export interface Playback {
  /** Ступени качества, какими движок знает их сейчас. У файла их нет. */
  readonly levels: Level[];
  /** Включить ступень: номер в {@link levels}, `-1` — выбирать самому. */
  quality(index: number): void;
  /** Включить дорожку звука по номеру в списке озвучек; ответ — её язык, пусто — если её нет. */
  voice(index: number): string;
  /** Субтитры из самого потока: номер дорожки, `-1` — выключить. */
  subtitles?(track: number): void;
  /** Начать загрузку заново — у эфира это его край, когда сам край ещё неизвестен. */
  reload?(): void;
  /** Край живого эфира на шкале `<video>`, секунды; `null` — ещё неизвестен. */
  readonly liveSyncPosition?: number | null;
  /** Время эфира у текущего кадра (`EXT-X-PROGRAM-DATE-TIME`); `null` — поток его не пишет. */
  readonly playingDate?: Date | null;
  /** Что движок знает о своей загрузке — для лестницы лечения (`stall.ts`). Нет — судим по `<video>`. */
  health?(): Omit<Health, 'ahead'>;
  /**
   * Ступень лечения застрявшего плеера (`stall.ts`). `false` — у этого движка такой нет, лестница идёт
   * дальше. `reopen` и `fail` решает тот, кто держит плеер (`usePlayback`), а не движок.
   */
  heal?(heal: Exclude<Heal, 'reopen' | 'fail'>): boolean;
  /**
   * Устройство не тянет нынешнюю картинку (`decode.ts`): тот же кадр кодеком легче (`codec` — от какого
   * отказались), а если легче нет — у автоматики ступень ниже (`level`). `null` — облегчать нечего.
   */
  lighten?(): { codec: VideoFamily } | { level: number } | null;
  destroy(): void;
}
