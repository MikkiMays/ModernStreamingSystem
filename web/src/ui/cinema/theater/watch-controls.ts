/**
 * Решения пульта кинозала, которые можно проверить без плеера.
 *
 * Здесь живут три правила, из-за которых жаловались на просмотр с телефона: что означает
 * нажатие по кадру, куда попадает перемотка на пятнадцать секунд и когда пульт уходит с
 * экрана. В самом {@link WatchTheater} они были выражениями внутри разметки — а такие
 * выражения проверяются только глазами и только там, где плеер вообще заводится.
 */

/** Что делать с нажатием по самому кадру. */
export type FramePress = 'wake' | 'toggle' | 'none';

/**
 * Нажали по кадру — показать пульт или остановить кино.
 *
 * ПАЛЬЦЕМ И ВО ВЕСЬ ЭКРАН — только показать. Палец не умеет наводиться: первое касание
 * спящего плеера означает «покажи, что тут есть», и принимать его за паузу значит
 * останавливать кино каждый раз, когда до экрана дотронулись, чтобы посмотреть время.
 * Пауза там — отдельная кнопка посреди кадра, мимо которой не промахиваются.
 *
 * МЫШЬЮ В ОКНЕ — остановить, как было: указатель наводится заранее, пульт под ним уже виден,
 * и клик по кадру — привычный способ поставить паузу.
 *
 * У эфира паузы нет вовсе, а у того, кому комната не дала трогать интеграции, нет права на
 * неё: обоим нажатие всё равно показывает пульт, иначе кадр выглядел бы мёртвым.
 */
export function framePress(context: {
  coarse: boolean;
  fullscreen: boolean;
  live: boolean;
  canControl: boolean;
}): FramePress {
  if (context.coarse || context.fullscreen) return 'wake';
  if (context.live || !context.canControl) return 'none';
  return 'toggle';
}

/**
 * Куда встанет перемотка на пятнадцать секунд.
 *
 * Не дальше начала и не дальше конца: отрицательная позиция — это ошибка ядра, а позиция за
 * концом ролика — мгновенный «досмотрели» у всей комнаты. Пока длительность неизвестна
 * (ролик ещё открывается), ограничиваем только снизу.
 */
export function skipTarget(positionMs: number, deltaMs: number, durationMs: number): number {
  const at = positionMs + deltaMs;
  return Math.round(Math.max(0, durationMs > 0 ? Math.min(at, durationMs) : at));
}

/**
 * Виден ли пульт.
 *
 * Раньше здесь стояло ещё и «показывать, пока не играет»: на паузе пульт не прятался никогда,
 * а вместе с ним оставался на кадре и курсор — в полноэкранном режиме это выглядело как
 * зависшее меню поверх фильма. Остановленный кадр — такая же картинка, как идущий; пульт
 * возвращается от первого движения. А вот открытое меню закрывать под мышкой нельзя, и пока
 * плеер не готов, прятать нечего: там не пульт, а объяснение происходящего.
 */
export function controlsShown(context: { idle: boolean; menuOpen: boolean; ready: boolean }): boolean {
  return !context.idle || context.menuOpen || !context.ready;
}

/** Кнопка «играть/пауза» пульта: как называется, что шлёт комнате и какой у неё значок. */
export interface PlayToggle {
  label: 'Включить для всех' | 'Пауза для всех';
  command: 'watch.play' | 'watch.pause';
  icon: 'play' | 'pause';
}

/**
 * Что делает кнопка «играть/пауза» — она посреди кадра, она же в полосе пульта, и так же понимается
 * нажатие мышью по кадру.
 *
 * Имя и действие — от комнаты, а не от своего `<video>`: пауза общая. Но досмотренный до конца ролик
 * (`over`) — тоже «стоит»: паузы комната не ставила, её секунда ушла за конец, а свой плеер на
 * последнем кадре. Раньше кнопка звалась там «Пауза для всех» и слала `watch.pause`: первое нажатие
 * не делало ничего видимого, второе начинало заново. Теперь после конца она — «Включить для всех» и
 * шлёт `watch.play`, а тот у досмотренного начинает ролик заново для всех (`useRoomSync`).
 *
 * Значок — ещё и от своего плеера: комната уже играет, а свой ещё не пошёл, — это ▶, а не ❚❚.
 */
export function playToggle(context: { paused: boolean; over: boolean; playing: boolean }): PlayToggle {
  const stopped = context.paused || context.over;
  return {
    label: stopped ? 'Включить для всех' : 'Пауза для всех',
    command: stopped ? 'watch.play' : 'watch.pause',
    icon: stopped || !context.playing ? 'play' : 'pause',
  };
}
