/**
 * Кого показывать крупно в раскладке «Говорящий».
 *
 * ПОЧЕМУ ЭТО НЕ ОДНА СТРОКА. Наивное «крупно тот, кто сейчас говорит» невыносимо: SFU
 * сообщает говорящих несколько раз в секунду, и в живом разговоре — с «угу», паузами и
 * перебиваниями — крупная плитка начинает прыгать на каждом слоге. Смотреть на это
 * невозможно, и виновата не сеть, а само правило.
 *
 * ЧТО ВМЕСТО. Выбор залипает: пока кто-то держит слово, он остаётся крупным, а сменяется
 * только тогда, когда другой говорит **и** прежний замолчал. Молчание всей комнаты ничего не
 * меняет — крупным остаётся тот, кто говорил последним, потому что на него и смотрели.
 *
 * Закрепление сильнее голоса: это прямое указание человека, а голос — наблюдение.
 */
export interface FocusInput {
  /** Кого закрепили руками, если закрепили. */
  pinned: string | null;
  /** Кто говорит прямо сейчас, по данным SFU. */
  speaking: string[];
  /** Кто сейчас показан крупно. */
  current: string | null;
  /** Кто вообще есть на сцене, в порядке показа. */
  people: string[];
}

export function focusedParticipant({ pinned, speaking, current, people }: FocusInput): string | null {
  if (pinned && people.includes(pinned)) return pinned;
  // Тот, кто был крупным, ушёл — держаться больше не за кого.
  const held = current && people.includes(current) ? current : null;
  if (held && speaking.includes(held)) return held;
  const talking = speaking.find((id) => people.includes(id));
  if (talking) return talking;
  // Никто не говорит: оставляем прежнего, на него и смотрели. Если прежнего нет — первого.
  return held ?? people[0] ?? null;
}
