/**
 * Где раскладка встречи меняет форму — одним списком для кода и для CSS.
 *
 * Раскладку рисует CSS (`styles.css`, `room-layout.css`, `ui/cinema/cinema.css`), а часть решений
 * о ней принимает код: какую кнопку пульта унести в меню, когда панели встречи уступить место
 * кинозалу. Границы у них обязаны совпадать до пикселя. Иначе появляется полоса ширин, где CSS
 * уже перестроил экран, а код ещё нет: так каталог на 701–767 px открывался под листом панели —
 * код считал телефоном всё до 700 px, а лист начинался с 767. `matchMedia` берёт строки отсюда,
 * а `breakpoints.test.ts` сверяет, что в CSS стоят ровно они, — правка с одной стороны падает.
 *
 * Только `max-width`/`min-width`: запись диапазоном (`767px < width`) Safari понимает лишь с 16.4.
 */

/** Телефон: пульт звонка на всю ширину, часть его кнопок переезжает в меню. */
export const COMPACT = '(max-width: 700px)';

/** Панель встречи — нижний лист во всю сцену. */
export const SHEET = '(max-width: 767px)';

/**
 * Пульт звонка — настольный, с подписью «Показать экран» и разделителями: сразу за листом. Ему
 * нужно сжиматься, чтобы поместиться в сцену (`room-layout.css`), ровно с той же ширины.
 */
export const DOCK = '(min-width: 768px)';

/** Панель встречи — полоса поверх сцены, а не своя колонка рядом с ней. */
export const DRAWER = '(max-width: 1199px)';

/** Рядом с полосой панели кинозалу хватает места: пульт плеера не обрезается. */
export const ROOMY = '(min-width: 960px)';

